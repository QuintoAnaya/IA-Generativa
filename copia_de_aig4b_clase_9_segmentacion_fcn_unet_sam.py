def mask_centroid(mask_np: np.ndarray):
    """Devuelve (x, y) del centroide de los píxeles foreground, o None si no hay."""
    ys, xs = np.where(mask_np > 0.5)
    if len(xs) == 0:
        return None
    return int(xs.mean()), int(ys.mean())


def sam_predict(img_uint8_hwc: np.ndarray, point_xy: tuple) -> np.ndarray:
    """Predice máscara binaria de SAM con un único point prompt positivo."""
    predictor.set_image(img_uint8_hwc)
    masks, scores, _ = predictor.predict(
        point_coords=np.array([point_xy]),
        point_labels=np.array([1]),
        multimask_output=False,
    )
    return masks[0]  # [H, W] booleano

