"""## 3. Modelo 1 — FCN (Fully Convolutional Network)

Implementamos un **FCN mínimo** que refleja la receta del slide:

1. **Encoder convolucional** (ResNet18 sin las capas densas finales) → comprime la imagen.
2. **Convolución 1×1** → produce un mapa de logits con `num_classes` canales.
3. **Upsample bilineal** → estira el mapa hasta el tamaño original de la imagen.

**Lo que esperamos ver:** las máscaras predichas van a tener **bordes borrosos**, porque el upsample bilineal no recupera los detalles que se perdieron en el encoder. Este es exactamente el problema que motivó UNET.

"""

import torch.nn as nn
import torch.nn.functional as F
import torchvision.models as tv_models

class SimpleFCN(nn.Module):
    """FCN didáctico: encoder ResNet18 + 1x1 conv + upsample bilineal."""
    def __init__(self, num_classes: int = 1, pretrained: bool = True):
        super().__init__()
        weights = "DEFAULT" if pretrained else None
        backbone = tv_models.resnet18(weights=weights)
        # Encoder: todas las capas conv del ResNet (descartamos avgpool + fc)
        self.encoder = nn.Sequential(
            backbone.conv1, backbone.bn1, backbone.relu, backbone.maxpool,
            backbone.layer1, backbone.layer2, backbone.layer3, backbone.layer4,
        )
        # Clasificador 1x1: 512 canales del ResNet → num_classes
        self.classifier = nn.Conv2d(512, num_classes, kernel_size=1)

    def forward(self, x):
        original_size = x.shape[-2:]
        x = self.encoder(x)            # [B, 512, H/32, W/32]
        x = self.classifier(x)         # [B, C,   H/32, W/32]
        x = F.interpolate(x, size=original_size, mode="bilinear", align_corners=False)
        return x                       # [B, C,   H,    W]

# Test rápido de la arquitectura
device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
fcn = SimpleFCN(num_classes=1).to(device)
dummy = torch.randn(2, 3, 256, 256).to(device)
with torch.no_grad():
    out = fcn(dummy)
