fcn_train_time = time.time() - t0

fcn_test_dice = evaluate_dice(fcn, test_loader)
print(f"\n⏱ Tiempo de entrenamiento: {fcn_train_time:.1f} s")
print(f"📊 FCN — Dice en TEST: {fcn_test_dice:.4f}")

