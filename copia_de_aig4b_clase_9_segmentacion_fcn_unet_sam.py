"""### Funciones auxiliares de entrenamiento y métrica

Definimos un loop de entrenamiento corto y la métrica **Dice** — que vamos a reusar para los tres modelos. El Dice mide qué tan parecidas son dos máscaras (1 = idénticas, 0 = sin solape).

"""

from torch.utils.data import DataLoader
import segmentation_models_pytorch as smp

BATCH_SIZE = 16
EPOCHS = 10
LR = 1e-3

train_loader = DataLoader(train_ds, batch_size=BATCH_SIZE, shuffle=True,  num_workers=2)
val_loader   = DataLoader(val_ds,   batch_size=BATCH_SIZE, shuffle=False, num_workers=2)
test_loader  = DataLoader(test_ds,  batch_size=BATCH_SIZE, shuffle=False, num_workers=2)


def dice_score(pred_mask: torch.Tensor, true_mask: torch.Tensor, eps: float = 1e-6) -> float:
    """Dice score binario sobre tensores [B, 1, H, W] con valores en {0, 1}."""
    pred_mask = pred_mask.float()
    true_mask = true_mask.float()
    intersection = (pred_mask * true_mask).sum(dim=(1, 2, 3))
    union = pred_mask.sum(dim=(1, 2, 3)) + true_mask.sum(dim=(1, 2, 3))
    dice = (2 * intersection + eps) / (union + eps)
    return dice.mean().item()


def train_model(model, train_loader, val_loader, epochs=EPOCHS, lr=LR):
    model.to(device)
    optimizer = torch.optim.Adam(model.parameters(), lr=lr)
    loss_fn = smp.losses.DiceLoss(smp.losses.BINARY_MODE, from_logits=True)

    history = {"train_loss": [], "val_dice": []}
    for epoch in range(epochs):
        model.train()
        epoch_loss = 0.0
        for x, y in train_loader:
            x, y = x.to(device), y.to(device)
            optimizer.zero_grad()
            logits = model(x)
            loss = loss_fn(logits, y)
            loss.backward(); optimizer.step()
            epoch_loss += loss.item() * x.size(0)
        epoch_loss /= len(train_loader.dataset)

        # Validación
        model.eval()
        val_dices = []
        with torch.no_grad():
            for x, y in val_loader:
                x, y = x.to(device), y.to(device)
                pred = (model(x).sigmoid() > 0.5).float()
                val_dices.append(dice_score(pred, y))
        val_dice = sum(val_dices) / len(val_dices)

        history["train_loss"].append(epoch_loss)
        history["val_dice"].append(val_dice)
        print(f"Epoch {epoch+1:2d}/{epochs} · loss={epoch_loss:.4f} · val Dice={val_dice:.4f}")
    return history


def evaluate_dice(model, loader) -> float:
    model.eval()
    dices = []
    with torch.no_grad():
        for x, y in loader:
            x, y = x.to(device), y.to(device)
            pred = (model(x).sigmoid() > 0.5).float()
            dices.append(dice_score(pred, y))
    return sum(dices) / len(dices)

